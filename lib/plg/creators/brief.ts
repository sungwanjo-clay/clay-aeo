/**
 * The full brief for one video idea as Markdown: everything the side panel shows, written so a person or an agent
 * (a scriptwriter, a creator-outreach agent) can pick it up with no other context. Downloaded or copied from the
 * Content insights tab.
 */
import type { CreatorsData, Rec } from './compute'
import { r1 } from './compute'
import { formatLabel, themeLabel } from './themes'
import { UTM, UTM_NOTE, trackedUrl, tracksUtm, utmName } from './utm'

const n = (x: number | null | undefined) => (x == null ? '–' : Math.round(x).toLocaleString('en-US'))
const yt = (id: string) => `https://www.youtube.com/watch?v=${id}`

export function briefMarkdown(r: Rec, d: CreatorsData): string {
  const s = d.scan!
  const ch = (c: string) => s.channels[c]?.t ?? 'unknown channel'
  const b = r.brief
  const L: string[] = []
  L.push(`# Video brief #${r.rank}: ${b.title}`, '')
  L.push(`Topic: ${r.label}${r.formatLabel ? ` · title format: ${r.formatLabel}` : ''} · niche scan of ${s.fetchedAt.slice(0, 10)} · program data through ${d.dataEnd}`)
  L.push(r.written ? 'Brief written in the weekly review from the evidence below.' : 'Draft brief: the title is the top copy’s, the use case, landing page and offer are the theme’s default play. Rewrite before sending.', '')
  L.push('## Context', '', 'Clay sponsors YouTube creators in the GTM, cold email and AI lead-gen niche. Each video gets its own ?via= link; success is new Clay workspaces per 1,000 views (1+ with 10+ workspaces = worked, under 0.25 = failed). This brief comes from a weekly scan of what the niche watches (views against each channel’s own median) and from what our sponsored videos drove in signups.', '')
  L.push('## Sourced from', '')
  L.push(`### Copies that worked in the niche`, '', 'Other creators’ videos: they carry no Clay link, so there are no signups to report, only views against the channel’s own median.', '')
  for (const v of r.examples) L.push(`- “${v.t}”, ${ch(v.c)}: ${r1(v.x)}× the channel’s median (${n(v.v)} views), ${v.m} min, published ${v.p} (${yt(v.id)})`)
  if (r.losers.length) { L.push('', '### Copies that failed (under 0.7× their channel)', ''); for (const v of r.losers) L.push(`- “${v.t}”, ${ch(v.c)}: ${n(v.v)} views, ${r1(v.x)}× (${yt(v.id)})`) }
  L.push('', `### Our sponsored videos on this ${r.oursScope} (signups)`, '')
  if (r.ours.length) for (const v of r.ours) L.push(`- “${v.title}”, ${v.creator} (${v.placement}): ${n(v.views)} views, ${n(v.m.ws)} new workspaces, ${n(v.m.t13)} Tier 1–3, ${v.perK == null ? 'shared link' : `${r1(v.perK)} per 1K views`}, result: ${v.result}`)
  else L.push('- None yet: this idea is also a test of whether the theme converts.')
  L.push('', '## The brief', '')
  const rows: [string, string | null][] = [['Title', b.title], ['Use case to show', b.useCase], ['Related resources', b.resources.map(x => (x.url ? `${x.label} (${x.url})` : x.label)).join('; ')], ['Offer', b.offer], ['CTA', b.cta], ['Thumbnail', b.thumbnail], ['Structure', b.structure], ['Angle', r.angle]]
  for (const [k, v] of rows) if (v) L.push(`- **${k}:** ${v}`)
  const tgt = b.resources.find(x => x.url && tracksUtm(x.url)) ?? b.resources.find(x => x.url)
  if (tgt?.url) {
    const key = utmName(r.title)
    L.push('', '## Tracked link', '', `${UTM.campaignType}, tactic ${UTM.tactic}. Add the creator's first name to the end of the utm name (\`${key}_<name>\`) and use the same name in the link and the campaign.`, '',
      `- **Link:** ${trackedUrl(tgt.url, key)}`, `- **utm campaign name:** ${key}`,
      '- **Campaign:** the link is credited only once a campaign with this utm name exists. Create it with /campaign-create before the video goes live.')
    if (!tracksUtm(tgt.url)) L.push(`- **Note:** ${UTM_NOTE}`)
  }
  L.push('', '## Why each decision', '')
  for (const x of r.reasons) L.push(`- **${x.label}** (${x.src === 'review' ? 'weekly review' : x.src === 'default' ? 'theme default' : 'from the data'}): ${x.why}`)
  L.push('', '## Evidence summary', '', ...r.why.map(w => `- ${w}`))
  if (r.seps.length) {
    L.push('', '## What separates copies that worked from ones that failed on this theme', '', '| Trait | Worked | Failed |', '|---|---|---|')
    for (const x of r.seps) L.push(`| ${x.label} | ${Math.round((100 * x.w) / x.wn)}% (${x.w}) | ${Math.round((100 * x.f) / x.fn)}% (${x.f}) |`)
  }
  L.push('', '## Measure it', '', ...r.measure.map(([k, v]) => `- **${k}:** ${v}`))
  if (r.formats.length) { L.push('', '## Title formats tried on this topic', '', '| Format | Copies | Worked |', '|---|---|---|'); for (const f of r.formats) L.push(`| ${formatLabel(f.f)} | ${f.n} | ${f.worked} (${Math.round((100 * f.worked) / f.n)}%) |`) }
  L.push('', `_Theme “${themeLabel(r.theme)}”${r.format ? `, format “${formatLabel(r.format)}”` : ''}. Generated by the Content insights tab; numbers are lifetime since Apr 6 for the program and the scan’s pull for the niche._`)
  return L.join('\n')
}
